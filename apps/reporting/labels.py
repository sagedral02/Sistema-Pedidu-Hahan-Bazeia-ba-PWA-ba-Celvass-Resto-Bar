# Labels added with the per-item / take-away / shift work (one JSON shared with static/js/i18n.js).
import json as _json  # noqa: E402
from pathlib import Path as _Path  # noqa: E402

for _lang, _extra in _json.loads((_Path(__file__).with_name('labels_feature.json')).read_text(encoding='utf-8')).items():
    LABELS[_lang].update(_extra)


def normalize_lang(lang):
    """Return a supported language code, falling back to the default (Tetun)."""
    return lang if lang in LABELS else DEFAULT_LANG


def label(lang, key, **kwargs):
    """Translate a report label. Falls back to Tetun, then English, then the key itself."""
    for code in (normalize_lang(lang), DEFAULT_LANG, 'en'):
        text = LABELS[code].get(key)
        if text is not None:
            return text.format(**kwargs) if kwargs else text
    return key
